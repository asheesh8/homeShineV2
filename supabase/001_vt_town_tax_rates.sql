-- Vermont municipal tax rate table
-- Vermont base state rate: 6.00%
-- Towns that have adopted the Local Option Tax add 1.00% → total 7.00%
-- Source: Vermont Department of Taxes — Local Option Tax list

CREATE TABLE IF NOT EXISTS vt_town_tax_rates (
  id           SERIAL PRIMARY KEY,
  town         TEXT NOT NULL,
  state_rate   NUMERIC(6,4) NOT NULL DEFAULT 0.0600,
  local_rate   NUMERIC(6,4) NOT NULL DEFAULT 0.0000,
  total_rate   NUMERIC(6,4) GENERATED ALWAYS AS (state_rate + local_rate) STORED,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Case-insensitive unique index on town name
CREATE UNIQUE INDEX IF NOT EXISTS idx_vt_town_tax_rates_town
  ON vt_town_tax_rates (LOWER(town));

